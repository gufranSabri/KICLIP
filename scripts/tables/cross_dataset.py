#!/usr/bin/env python3
# Scans runs/ for K400-trained runs and emits the cross-dataset table per method, next to FROSTER's paper numbers.
#
#     bash scripts/experiments/cross_dataset.sh
#     python scripts/tables/cross_dataset.py

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO_ROOT))

from scripts.tables.collect_runs import METHOD_PRETTY, METHODS, fmt, load_runs, mean_std  # noqa: E402

TRAIN = "cross/k400/train"
COLUMNS = [
    ("UCF*", ["cross/ucf101/full"], "85.0"),
    ("UCF", ["cross/ucf101/split1", "cross/ucf101/split2", "cross/ucf101/split3"], "84.8 ± 1.1"),
    ("HMDB*", ["cross/hmdb51/full"], "54.5"),
    ("HMDB", ["cross/hmdb51/split1", "cross/hmdb51/split2", "cross/hmdb51/split3"], "54.8 ± 1.3"),
    ("K-600", ["cross/k600/split1", "cross/k600/split2", "cross/k600/split3"], "74.8 ± 0.9"),
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs-root", default=str(REPO_ROOT / "runs"))
    ap.add_argument("--out", default=str(REPO_ROOT / "docs" / "tables"))
    args = ap.parse_args()

    runs_root, out_dir = Path(args.runs_root), Path(args.out)
    if not runs_root.is_dir():
        raise SystemExit(f"no runs directory at {runs_root}")
    out_dir.mkdir(parents=True, exist_ok=True)

    runs = [r for r in load_runs(runs_root) if r["train"] == TRAIN and r["tests"]]
    runs.sort(key=lambda r: (METHODS.index(r["method"]), r["run"]))
    print(f"loaded {len(runs)} cross-dataset run(s) from {runs_root}")

    lines = [
        "### Cross-dataset: top-1 accuracy (%), trained on K-400",
        "",
        "| Method | Run | " + " | ".join(c[0] for c in COLUMNS) + " |",
        "|---|---|" + "---|" * len(COLUMNS),
        "| FROSTER (paper) | - | " + " | ".join(c[2] for c in COLUMNS) + " |",
    ]
    rows = []
    for r in runs:
        cells, values = [], []
        for _, splits, _ in COLUMNS:
            found = [r["tests"][s]["top1"] for s in splits if s in r["tests"]]
            m, s = mean_std(found) if len(found) == len(splits) else (None, None)
            cells.append(fmt(m, s if len(splits) > 1 else None))
            values.append(m)
        lines.append(f"| {METHOD_PRETTY[r['method']]} | {r['run']} ({r['arch']}) | " + " | ".join(cells) + " |")
        rows.append([r["method"], r["run"], r["arch"]] + values)

    lines += [
        "",
        "`*` = the full validation set, otherwise mean ± std over the three splits. Generated by "
        "`scripts/experiments/cross_dataset.sh` + `scripts/tables/cross_dataset.py`.",
        "",
    ]
    md_dest = out_dir / "cross_dataset.md"
    md_dest.write_text("\n".join(lines))
    print(f"  wrote {md_dest}")

    csv_dest = out_dir / "cross_dataset.csv"
    with open(csv_dest, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["method", "run", "arch"] + [c[0] for c in COLUMNS])
        for row in rows:
            w.writerow(["" if v is None else (f"{v:.4f}" if isinstance(v, float) else v) for v in row])
    print(f"  wrote {csv_dest}")


if __name__ == "__main__":
    main()
