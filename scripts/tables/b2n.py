#!/usr/bin/env python3
# Scans runs/ for base-to-novel runs and emits the B2N table per method (mean over seeds), with FROSTER's paper numbers.
#
#     bash scripts/experiments/b2n.sh
#     python scripts/tables/b2n.py

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO_ROOT))

from scripts.tables.collect_runs import METHOD_PRETTY, METHODS, fmt, load_runs, mean_std  # noqa: E402
from src.utils.metrics import harmonic_mean  # noqa: E402

DATASETS = ["k400", "hmdb51", "ucf101", "ssv2"]
DATASET_PRETTY = {"k400": "K-400", "hmdb51": "HMDB-51", "ucf101": "UCF-101", "ssv2": "SSv2"}
PAPER = {
    # "k400": (77.8, 64.3, 70.4),
    # "hmdb51": (74.1, 58.0, 65.1),
    # "ucf101": (95.3, 80.0, 87.0),
    # "ssv2": (18.3, 12.2, 14.6),
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs-root", default=str(REPO_ROOT / "runs"))
    ap.add_argument("--out", default=str(REPO_ROOT / "docs" / "tables"))
    args = ap.parse_args()

    runs_root, out_dir = Path(args.runs_root), Path(args.out)
    if not runs_root.is_dir():
        raise SystemExit(f"no runs directory at {runs_root}")
    out_dir.mkdir(parents=True, exist_ok=True)
    runs = load_runs(runs_root)

    lines = [
        "### Base-to-novel: top-1 accuracy (%), mean ± std over seeds",
        "",
        "| Dataset | Method | Seeds | Base | Novel | HM |",
        "|---|---|---|---|---|---|",
    ]
    rows = []
    for ds in DATASETS:
        lines.append(f"| {DATASET_PRETTY[ds]} | FROSTER (paper) | - | " + " | ".join(map(str, PAPER[ds])) + " |")
        for method in METHODS:
            base, novel, hm, seeds = [], [], [], []
            for r in runs:
                b, n = r["tests"].get(f"b2n/{ds}/base"), r["tests"].get(f"b2n/{ds}/novel")
                if r["method"] != method or not r["train"].startswith(f"b2n/{ds}/train_") or b is None or n is None:
                    continue
                seeds.append(r["train"].rsplit("_", 1)[-1])
                base.append(b["top1"])
                novel.append(n["top1"])
                hm.append(harmonic_mean(b["top1"], n["top1"]))
            if not seeds:
                continue
            stats = [mean_std(v) for v in (base, novel, hm)]
            lines.append(f"| {DATASET_PRETTY[ds]} | {METHOD_PRETTY[method]} | {','.join(sorted(seeds))} | "
                         + " | ".join(fmt(*s) for s in stats) + " |")
            rows.append([ds, method, len(seeds)] + [s[0] for s in stats])
            print(f"  {ds:7s} {method:20s} seeds={sorted(seeds)}")

    lines += [
        "",
        "HM is the harmonic mean of base and novel, computed per seed then averaged. Base = the base classes' "
        "val videos, novel = the novel classes'. Generated by `scripts/experiments/b2n.sh` + `scripts/tables/b2n.py`.",
        "",
    ]
    md_dest = out_dir / "b2n.md"
    md_dest.write_text("\n".join(lines))
    print(f"  wrote {md_dest}")

    csv_dest = out_dir / "b2n.csv"
    with open(csv_dest, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["dataset", "method", "seeds", "base", "novel", "hm"])
        for row in rows:
            w.writerow([f"{v:.4f}" if isinstance(v, float) else v for v in row])
    print(f"  wrote {csv_dest}")


if __name__ == "__main__":
    main()
