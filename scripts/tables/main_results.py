#!/usr/bin/env python3
# Main results table: for each dataset, the best full-DCGD run (drift damping + CGAS both on) by HM,
# searched across every run under --runs-root, not just runs/main -- sweeps (pooling, capacity, distill/cgas
# weight, ...) often land a better seed/setting than the one-off runs/main checkpoint for that dataset.
#
#     python scripts/tables/main_results.py

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO_ROOT))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs-root", default=str(REPO_ROOT / "runs"))
    args = ap.parse_args()
    runs_root = Path(args.runs_root)

    best_per_dataset: dict[str, tuple[str, dict]] = {}
    for config_path in sorted(runs_root.rglob("config.json")):
        run_dir = config_path.parent
        try:
            cfg = json.loads(config_path.read_text())
        except json.JSONDecodeError:
            continue
        model = cfg.get("model", {})
        if not model.get("drift_damping") or model.get("cgas_source") not in ("student", "teacher", "both"):
            continue
        results_path = run_dir / "results.json"
        if not results_path.exists():
            continue
        try:
            results = json.loads(results_path.read_text())
        except json.JSONDecodeError:
            continue
        if "HM" not in results:
            continue
        dataset = cfg["data"]["train"].split("/")[1]
        name = str(run_dir.relative_to(runs_root))
        if dataset not in best_per_dataset or results["HM"] > best_per_dataset[dataset][1]["HM"]:
            best_per_dataset[dataset] = (name, results)

    lines = [
        "### Main Results: Best DCGD Run Per Dataset",
        "",
        "| Dataset | Run | Base | Novel | HM |",
        "|---|---|---|---|---|",
    ]
    rows = []
    for dataset in sorted(best_per_dataset):
        name, best = best_per_dataset[dataset]
        lines.append(
            f"| {dataset.upper()} | {name} | {best['base']['top1']:.1f} | "
            f"{best['novel']['top1']:.1f} | {best['HM']:.1f} |"
        )
        rows.append([dataset, name, best["base"]["top1"], best["novel"]["top1"], best["HM"]])
        print(f"  {dataset:10s} best={name:45s} HM={best['HM']:.2f}")

    lines += [
        "",
        "Best run per dataset is the full DCGD run (drift damping + CGAS both on, model.drift_damping=true, "
        "model.cgas_source set) with the highest HM, searched across every run under runs/. HM is the harmonic "
        "mean of base and novel top-1 accuracy. Generated by `scripts/tables/main_results.py`.",
        "",
    ]
    out_dir = REPO_ROOT / "docs" / "tables"
    out_dir.mkdir(parents=True, exist_ok=True)
    md_dest = out_dir / "main_results.md"
    md_dest.write_text("\n".join(lines))
    print(f"  wrote {md_dest}")

    csv_dest = out_dir / "main_results.csv"
    with open(csv_dest, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["dataset", "run", "base", "novel", "hm"])
        for row in rows:
            w.writerow([row[0], row[1]] + [f"{v:.4f}" for v in row[2:]])
    print(f"  wrote {csv_dest}")


if __name__ == "__main__":
    main()
