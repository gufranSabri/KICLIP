#!/usr/bin/env python3
# Scans runs/ for every b2n run (grouped by dataset, parsed from config.json's data.train), finds
# the highest-HM run per dataset, and writes its full resolved config as a self-contained overlay to
# configs/b2n/best/<dataset>.yaml (only the keys that differ from configs/default.yaml). Also propagates
# that overlay's model: block onto configs/fewshot/best/<dataset>.yaml and configs/cross/best/<dataset>.yaml
# (combined with THEIR OWN data:/train: block from configs/{fewshot,cross}/default/<dataset>.yaml),
# wherever such a default config exists -- fewshot/cross have no sweep of their own, so they just reuse
# whatever hyperparameters b2n found best for that dataset. Rerun after a sweep to refresh every pick;
# scripts/run_{b2n,fewshot,zeroshot}.sh use their own best/<ds>.yaml when present.
#
#     python scripts/pick_best_config.py [--runs-root runs] [--out configs/b2n/best]

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

import yaml  # noqa: E402

DEFAULT_CONFIG = REPO_ROOT / "configs" / "default.yaml"


def dataset_of(train_split: str) -> tuple[str, str] | None:
    # "b2n/hmdb51/train_s1" -> ("b2n", "hmdb51"); None for anything not under b2n/
    parts = train_split.split("/")
    return (parts[0], parts[1]) if len(parts) == 3 and parts[0] == "b2n" else None


def diff(resolved: dict, base: dict) -> dict:
    out = {}
    for key, val in resolved.items():
        if key not in base:
            out[key] = val
        elif isinstance(val, dict) and isinstance(base[key], dict):
            sub = diff(val, base[key])
            if sub:
                out[key] = sub
        elif val != base[key]:
            out[key] = val
    return out


def best_per_dataset(runs_root: Path) -> dict[str, tuple[float, Path]]:
    best: dict[str, tuple[float, Path]] = {}
    for results_path in runs_root.rglob("results.json"):
        run_dir = results_path.parent
        config_path = run_dir / "config.json"
        if not config_path.exists():
            continue
        results = json.loads(results_path.read_text())
        if "HM" not in results:
            continue
        config = json.loads(config_path.read_text())
        parsed = dataset_of(config["data"]["train"])
        if parsed is None:
            continue
        _, dataset = parsed
        hm = results["HM"]
        if dataset not in best or hm > best[dataset][0]:
            best[dataset] = (hm, run_dir)
    return best


def propagate(protocol: str, dataset: str, model_block: dict, hm: float, run_dir: Path) -> bool:
    # writes configs/<protocol>/best/<dataset>.yaml from THAT protocol's own default/<dataset>.yaml
    # data:/train: block plus the b2n-best model: block; no-op if that protocol has no such dataset
    default_path = REPO_ROOT / "configs" / protocol / "default" / f"{dataset}.yaml"
    if not default_path.exists():
        return False
    own = yaml.safe_load(default_path.read_text()) or {}
    overlay = {"model": model_block, **{k: v for k, v in own.items() if k != "model"}}
    out_dir = REPO_ROOT / "configs" / protocol / "best"
    out_dir.mkdir(parents=True, exist_ok=True)
    header = (f"# {protocol} config for {dataset}: model hyperparameters from the b2n best run "
             f"(HM {hm:.2f}, {run_dir}); data from configs/{protocol}/default/{dataset}.yaml "
             f"(generated by scripts/pick_best_config.py)\n")
    (out_dir / f"{dataset}.yaml").write_text(header + yaml.safe_dump(overlay, sort_keys=False, default_flow_style=None))
    return True


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs-root", default=str(REPO_ROOT / "runs"))
    ap.add_argument("--out", default=str(REPO_ROOT / "configs" / "b2n" / "best"))
    args = ap.parse_args()

    runs_root, out_dir = Path(args.runs_root), Path(args.out)
    if not runs_root.is_dir():
        raise SystemExit(f"no runs directory at {runs_root}")
    base = yaml.safe_load(DEFAULT_CONFIG.read_text())

    picks = best_per_dataset(runs_root)
    if not picks:
        raise SystemExit(f"no b2n run under {runs_root} has a results.json with HM")

    out_dir.mkdir(parents=True, exist_ok=True)
    for dataset, (hm, run_dir) in sorted(picks.items()):
        config = json.loads((run_dir / "config.json").read_text())
        overlay = diff(config, base)
        header = f"# best b2n config for {dataset}: HM {hm:.2f} from {run_dir} (generated by scripts/pick_best_config.py)\n"
        (out_dir / f"{dataset}.yaml").write_text(header + yaml.safe_dump(overlay, sort_keys=False, default_flow_style=None))
        print(f"  {dataset:10s} HM {hm:6.2f}  <- {run_dir}")

        for protocol in ("fewshot", "cross"):
            if propagate(protocol, dataset, overlay.get("model", {}), hm, run_dir):
                print(f"    -> also wrote configs/{protocol}/best/{dataset}.yaml")
    print(f"wrote {out_dir}/<dataset>.yaml")


if __name__ == "__main__":
    main()
